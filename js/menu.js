function createCard(item) {

    const imageName = item.name
        .replace(/[()&/+]/g, "")
        .replace(/\s+/g, "_");

    const imageUrl = item.image || 
        `https://res.cloudinary.com/uzhcoc7h/image/upload/f_auto,q_auto/${imageName}`;

    return `
        <div class="dish-card">

            <img
                src="${imageUrl}"
                loading="lazy"
                decoding="async"
                alt="${item.name}"
            >

            <div class="dish-overlay">

                <h5>${item.name}</h5>

                <div class="meta">

                    <span class="price">
                        ${item.price || "Price unavailable"}
                    </span>

                  

                </div>

            </div>

        </div>
    `;
}


// MAIN PAGE PAR SIRF 4 CARDS

menuContainers.forEach(container => {

    const category = container.dataset.category;

    const items = menuItems.filter(
        item => item.category === category
    );

    container.innerHTML = items
        .slice(0, 4)
        .map(item => createCard(item))
        .join("");

});


// VIEW ALL → POPUP

// ============================================
// VIEW ALL → POPUP + SEARCH
// ============================================

document.querySelectorAll(".view-all-btn").forEach(button => {

    button.addEventListener("click", function () {

        const category = this.dataset.category;

        // Current category ke dishes save karo
        currentModalItems = menuItems.filter(
            item => item.category === category
        );

        // Modal title
        modalTitle.textContent = category;

        // Search reset
        menuSearchInput.value = "";

        // Saare dishes show
        renderModalItems(currentModalItems);

        // Popup open
        menuModal.classList.add("active");

        document.body.style.overflow = "hidden";

        // Search input par focus
        setTimeout(() => {
            menuSearchInput.focus();
        }, 200);

    });

});


// ============================================
// RENDER MODAL ITEMS
// ============================================

function renderModalItems(items) {

    if (items.length === 0) {

        modalMenuContainer.innerHTML = `
            <div class="no-dishes-found">
                <i class="fas fa-search"></i>
                <h3>No dishes found</h3>
                <p>Try searching with another dish name.</p>
            </div>
        `;

        return;
    }

    modalMenuContainer.innerHTML = items
        .map(item => createCard(item))
        .join("");
}


